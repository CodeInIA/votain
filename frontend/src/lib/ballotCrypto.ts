/**
 * The arithmetic of a Votain ballot, and the proof that a tally is correct.
 *
 * WHY THIS SCHEME. Ballots are exponential ElGamal over Baby Jubjub, the
 * curve the ballot circuit (circuits/src/ballot.circom) can compute on, which
 * is what lets a voter prove a ballot well formed AND cancel their previous one
 * without revealing which. See the circuit for the construction. A ballot is:
 *
 *   vote    A  = r·G,              B_i  = v_i·G + r·H_i
 *   cancel  A' = -A_prev + s·G,    B'_i = -B_prev_i + s·H_i
 *
 * with one tally key H_i = x_i·G per slot (options plus the blank vote).
 * Adding every vote and every cancellation on chain telescopes each voter's
 * chain to their LAST vote, so the aggregate decrypts straight to the counts:
 *
 *   M_i = ΣB_i - x_i·ΣA = count_i·G
 *
 * and count_i is recovered by a baby-step giant-step search, bounded by the
 * number of ballots.
 *
 * THE PROOF that a tally is right is the tally circuit's
 * (circuits/src/tally.circom), checked by the election on chain against the
 * aggregate it accumulated itself; nothing here needs to be trusted for it.
 *
 * Deliberately free of dependencies, like the module it replaces: the browser,
 * the auditor's CLI and the contract tests import this one file. Poseidon is
 * passed in where it is needed, since each of them already has one.
 */

