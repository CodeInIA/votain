/**
 * One key per slot, derived from a 32-byte secret and a per-election nonce.
 *
 * 48 bytes of HMAC output per key, reduced modulo l, so the reduction bias is
 * below 2^-128. The public keys are what the election stores.
 */
export async function deriveTallyKeys(
  secret: Uint8Array,
  keyNonce: string,
  slots: number,
): Promise<{ secrets: bigint[]; keys: Point[] }> {
  const key = await crypto.subtle.importKey(
    "raw",
    // A copy: a plain ArrayBuffer-backed view is what every WebCrypto accepts,
    // the browser's and Node's, whose type declarations differ.
    new Uint8Array(secret),
    { name: "HMAC", hash: "SHA-256" },
    false,
    ["sign"],
  );
  const secrets: bigint[] = [];
  for (let i = 0; i < slots; i++) {
    const label = (part: number) => new TextEncoder().encode(`votain:tally-key:v2:${keyNonce}:${i}:${part}`);
    const one = new Uint8Array(await crypto.subtle.sign("HMAC", key, label(0)));
    const two = new Uint8Array(await crypto.subtle.sign("HMAC", key, label(1)));
    const x = bytesToBigInt(new Uint8Array([...one, ...two.slice(0, 16)])) % SUBGROUP_ORDER;
    secrets.push(x === 0n ? 1n : x);
  }
  return { secrets, keys: secrets.map(x => multiply(BASE, x)) };
}

