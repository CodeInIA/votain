/** A LeanIMT membership proof, as @zk-kit/lean-imt produces it. */
export interface MerklePath {
  root: bigint;
  index: number | bigint;
  siblings: readonly bigint[];
}

/** Depth the ballot circuit was compiled for, for both of its trees. */
export const CIRCUIT_MAX_DEPTH = 20;

const toStrings = (values: readonly bigint[]): string[] => values.map(v => v.toString());
const pointStrings = (p: Point): string[] => [p[0].toString(), p[1].toString()];

function pathInputs(path: MerklePath | null, maxDepth: number) {
  if (!path) return { depth: "0", index: "0", siblings: Array.from({ length: maxDepth }, () => "0") };
  if (path.siblings.length > maxDepth) throw new Error("tree deeper than the circuit supports");
  return {
    depth: String(path.siblings.length),
    index: BigInt(path.index).toString(),
    siblings: toStrings([...path.siblings, ...Array.from({ length: maxDepth - path.siblings.length }, () => 0n)]),
  };
}

/** What a cast ballot carries on chain, padded to the circuit's slots. */
export interface CastBallot {
  tag: bigint;
  epochTag: bigint;
  leaf: bigint;
  voteA: Point;
  voteB: Point[];
  cancelA: Point;
  cancelB: Point[];
}

/**
 * Everything the ballot circuit needs to prove one ballot, and the ballot.
 *
 * `keys` are the election's own slots; the circuit's extra slots are padded
 * with the identity, which is what `keysHash` hashes too. `previous` is the
 * voter's own last ballot and its path in the ballots tree, or null for their
 * first.
 */
export function ballotCircuitInputs(p: {
  poseidon3: Poseidon;
  poseidon4: Poseidon;
  circuitSlots: number;
  maxDepth?: number;
  secret: bigint;
  scope: bigint;
  epoch: bigint;
  keys: readonly Point[];
  choice: number;
  k: bigint;
  voters: MerklePath;
  ballotsRoot: bigint;
  previous: { a: Point; b: readonly Point[]; path: MerklePath } | null;
  r?: bigint;
  s?: bigint;
}): { inputs: Record<string, string | string[] | string[][]>; ballot: CastBallot } {
  const maxDepth = p.maxDepth ?? CIRCUIT_MAX_DEPTH;
  const keys = padPoints(p.keys, p.circuitSlots);
  const r = p.r ?? randomScalar();
  const s = p.s ?? randomScalar();

  // The encryption runs over the padded keys: identity keys give identity
  // components, which is what the circuit computes for unused slots.
  const vote = encryptVote(keys, p.choice, r);
  const previous = p.previous ? { a: p.previous.a, b: padPoints(p.previous.b, p.circuitSlots) } : null;
  const cancel = encryptCancellation(keys, s, previous);

  const tag = ballotTag(p.poseidon4, p.secret, p.scope, p.k);
  const ballot: CastBallot = {
    tag,
    epochTag: epochTag(p.poseidon4, p.secret, p.scope, p.epoch),
    leaf: ballotLeaf(p.poseidon3, tag, vote.a, vote.b),
    voteA: vote.a,
    voteB: vote.b,
    cancelA: cancel.a,
    cancelB: cancel.b,
  };

  const voters = pathInputs(p.voters, maxDepth);
  const ballots = pathInputs(p.previous?.path ?? null, maxDepth);
  const prevA = previous?.a ?? IDENTITY;
  const prevB = previous?.b ?? padPoints([], p.circuitSlots);

  return {
    ballot,
    inputs: {
      votersRoot: p.voters.root.toString(),
      ballotsRoot: p.ballotsRoot.toString(),
      scope: p.scope.toString(),
      keysHash: keysHash(p.poseidon3, p.keys, p.circuitSlots).toString(),
      slots: String(p.keys.length),
      epoch: p.epoch.toString(),
      voteA: pointStrings(vote.a),
      voteB: vote.b.map(pointStrings),
      cancelA: pointStrings(cancel.a),
      cancelB: cancel.b.map(pointStrings),
      secret: p.secret.toString(),
      votersDepth: voters.depth,
      votersIndex: voters.index,
      votersSiblings: voters.siblings,
      keys: keys.map(pointStrings),
      choice: Array.from({ length: p.circuitSlots }, (_, i) => (i === p.choice ? "1" : "0")),
      r: r.toString(),
      s: s.toString(),
      k: p.k.toString(),
      prevA: pointStrings(prevA),
      prevB: prevB.map(pointStrings),
      ballotsDepth: ballots.depth,
      ballotsIndex: ballots.index,
      ballotsSiblings: ballots.siblings,
    },
  };
}

/**
 * The inputs of the tally circuit, for publishing (`publish`) or for voiding
 * below the quorum. `aggregate` is the election's on-chain sum, padded.
 */
export function tallyCircuitInputs(p: {
  poseidon3: Poseidon;
  circuitSlots: number;
  keys: readonly Point[];
  secrets: readonly bigint[];
  counts: readonly bigint[];
  aggregate: { a: Point; b: readonly Point[] };
  quorum: bigint;
  publish: boolean;
}): Record<string, string | string[] | string[][]> {
  const pad = <T,>(values: readonly T[], filler: T) =>
    Array.from({ length: p.circuitSlots }, (_, i) => values[i] ?? filler);
  return {
    keysHash: keysHash(p.poseidon3, p.keys, p.circuitSlots).toString(),
    slots: String(p.keys.length),
    aggA: pointStrings(p.aggregate.a),
    aggB: padPoints(p.aggregate.b, p.circuitSlots).map(pointStrings),
    quorum: p.quorum.toString(),
    publish: p.publish ? "1" : "0",
    // An unused slot needs a valid scalar all the same; its key is forced to
    // the identity whatever this is.
    secrets: toStrings(pad(p.secrets, 1n)),
    count: toStrings(pad(p.counts, 0n)),
  };
}

