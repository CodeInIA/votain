/** One ballot as the chain records it: a vote and a cancellation. */
export interface Ballot {
  tag: bigint;
  voteA: Point;
  voteB: Point[];
  cancelA: Point;
  cancelB: Point[];
}

/** The vote part of a fresh ballot, for `slots` slots, voting `choice`. */
export function encryptVote(keys: readonly Point[], choice: number, r: bigint): { a: Point; b: Point[] } {
  if (!Number.isInteger(choice) || choice < 0 || choice >= keys.length) {
    throw new Error(`not an option index: ${choice}`);
  }
  return {
    a: multiply(BASE, r),
    b: keys.map((h, i) => add(i === choice ? BASE : IDENTITY, multiply(h, r))),
  };
}

/** The cancellation of `previous` (or of nothing), re-randomised with `s`. */
export function encryptCancellation(
  keys: readonly Point[],
  s: bigint,
  previous: { a: Point; b: readonly Point[] } | null,
): { a: Point; b: Point[] } {
  const prevA = previous?.a ?? IDENTITY;
  return {
    a: add(negate(prevA), multiply(BASE, s)),
    b: keys.map((h, i) => add(negate(previous?.b[i] ?? IDENTITY), multiply(h, s))),
  };
}

/** Everything cast, added up: one A and one B per slot. */
export function aggregate(ballots: readonly Ballot[], slots: number): { a: Point; b: Point[] } {
  let a: Point = IDENTITY;
  const b: Point[] = Array.from({ length: slots }, () => IDENTITY);
  for (const ballot of ballots) {
    a = add(add(a, ballot.voteA), ballot.cancelA);
    for (let i = 0; i < slots; i++) b[i] = add(add(b[i], ballot.voteB[i]), ballot.cancelB[i]);
  }
  return { a, b };
}

/**
 * The m with m·G = target, for 0 <= m <= bound, by baby-step giant-step.
 * Null when there is none, which on an honest chain cannot happen.
 */
export function discreteLog(target: Point, bound: number): bigint | null {
  const step = Math.max(1, Math.ceil(Math.sqrt(bound + 1)));
  const table = new Map<string, number>();
  let p: Point = IDENTITY;
  for (let j = 0; j < step; j++) {
    table.set(`${p[0]}:${p[1]}`, j);
    p = add(p, BASE);
  }
  const giant = negate(multiply(BASE, BigInt(step)));
  let gamma = target;
  for (let i = 0; i <= step; i++) {
    const j = table.get(`${gamma[0]}:${gamma[1]}`);
    if (j !== undefined) {
      const m = BigInt(i * step + j);
      return m <= BigInt(bound) ? m : null;
    }
    gamma = add(gamma, giant);
  }
  return null;
}

