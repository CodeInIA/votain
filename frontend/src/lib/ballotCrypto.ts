/** A Groth16 proof as snarkjs returns it. */
export interface SnarkProof {
  pi_a: readonly (string | bigint)[];
  pi_b: readonly (readonly (string | bigint)[])[];
  pi_c: readonly (string | bigint)[];
}

/** A Groth16 proof in the verifiers' calldata order: b's coordinates are swapped. */
export interface SolidityProof {
  a: [bigint, bigint];
  b: [[bigint, bigint], [bigint, bigint]];
  c: [bigint, bigint];
}

export function solidityProof(proof: SnarkProof): SolidityProof {
  const n = (v: string | bigint) => BigInt(v);
  return {
    a: [n(proof.pi_a[0]), n(proof.pi_a[1])],
    b: [
      [n(proof.pi_b[0][1]), n(proof.pi_b[0][0])],
      [n(proof.pi_b[1][1]), n(proof.pi_b[1][0])],
    ],
    c: [n(proof.pi_c[0]), n(proof.pi_c[1])],
  };
}

/** A cast ballot as `castVote` and `relayVote` take it. */
export function ballotCalldata(
  ballot: CastBallot,
  roots: { votersRoot: bigint; ballotsRoot: bigint; epoch: bigint },
) {
  return {
    votersRoot: roots.votersRoot,
    ballotsRoot: roots.ballotsRoot,
    epoch: roots.epoch,
    tag: ballot.tag,
    epochTag: ballot.epochTag,
    leaf: ballot.leaf,
    voteA: [...ballot.voteA] as [bigint, bigint],
    voteB: flattenPoints(ballot.voteB),
    cancelA: [...ballot.cancelA] as [bigint, bigint],
    cancelB: flattenPoints(ballot.cancelB),
  };
}
