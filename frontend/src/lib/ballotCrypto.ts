// The tally
// ────────────────────────────────────────────────

/**
 * The counts an aggregate decrypts to. Needs the keys.
 *
 * `bound` is the most any count can be, the number of ballots cast, which is
 * what keeps the discrete-log search short. Whether these counts reach the
 * chain is decided by the tally circuit, which proves them against the
 * aggregate the election itself accumulated.
 */
export function decryptTally(
  secrets: readonly bigint[],
  total: { a: Point; b: readonly Point[] },
  bound: number,
): bigint[] {
  return secrets.map((x, i) => {
    const m = add(total.b[i], negate(multiply(total.a, x)));
    const count = discreteLog(m, bound);
    if (count === null) throw new Error(`option ${i + 1} does not decrypt to a count of at most ${bound}`);
    return count;
  });
}

/** A key list as the contract stores it: x0, y0, x1, y1, ... */
export const flattenPoints = (points: readonly Point[]): bigint[] => points.flatMap(p => [p[0], p[1]]);

export function unflattenPoints(values: readonly bigint[]): Point[] {
  const out: Point[] = [];
  for (let i = 0; i + 1 < values.length; i += 2) out.push([values[i], values[i + 1]]);
  return out;
}

