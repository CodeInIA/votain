/** The BN254 scalar field: Baby Jubjub's base field and the circuit's field. */
export const FIELD = 21888242871839275222246405745257275088548364400416034343698204186575808495617n;
/** Order of the prime subgroup generated by `BASE`. */
export const SUBGROUP_ORDER = 2736030358979909402780800718157159386076813972158567259200215660948447373041n;

const A_COEFF = 168700n;
const D_COEFF = 168696n;

export type Point = readonly [bigint, bigint];

export const IDENTITY: Point = [0n, 1n];
/** Base8, the generator the circuit and Semaphore use. */
export const BASE: Point = [
  5299619240641551281634865583518297030282874472190772894086521144482721001553n,
  16950150798460657717958625567821834550301663161624707787222815936182638968203n,
];

const mod = (a: bigint, m: bigint = FIELD): bigint => ((a % m) + m) % m;


/** Modular inverse by extended Euclid, far cheaper than a Fermat power here. */
function inverse(a: bigint): bigint {
  let [oldR, r] = [mod(a), FIELD];
  let [oldS, s] = [1n, 0n];
  while (r !== 0n) {
    const q = oldR / r;
    [oldR, r] = [r, oldR - q * r];
    [oldS, s] = [s, oldS - q * s];
  }
  return mod(oldS);
}

/**
 * Extended twisted Edwards coordinates (X:Y:Z:T), x = X/Z, y = Y/Z, xy = T/Z.
 *
 * Additions need no inversion here, so a scalar multiplication pays for one,
 * at the end, instead of one per step: the difference between a tally that
 * takes seconds and one that takes minutes.
 */
type Extended = [bigint, bigint, bigint, bigint];

const toExtended = ([x, y]: Point): Extended => [x, y, 1n, mod(x * y)];

function toAffine([x, y, z]: Extended): Point {
  const zi = inverse(z);
  return [mod(x * zi), mod(y * zi)];
}

/** add-2008-hwcd: complete on Baby Jubjub, whose d is not a square. */
function addExtended(p: Extended, q: Extended): Extended {
  const [x1, y1, z1, t1] = p;
  const [x2, y2, z2, t2] = q;
  const a = mod(x1 * x2);
  const b = mod(y1 * y2);
  const c = mod(D_COEFF * t1 * t2);
  const d = mod(z1 * z2);
  const e = mod((x1 + y1) * (x2 + y2) - a - b);
  const f = mod(d - c);
  const g = mod(d + c);
  const h = mod(b - A_COEFF * a);
  return [mod(e * f), mod(g * h), mod(f * g), mod(e * h)];
}

/** Twisted Edwards addition, complete on Baby Jubjub. */
export function add(p: Point, q: Point): Point {
  return toAffine(addExtended(toExtended(p), toExtended(q)));
}

export const negate = (p: Point): Point => [mod(-p[0]), p[1]];

function multiplyExtended(p: Point, scalar: bigint): Point {
  let result: Extended = [0n, 1n, 1n, 0n];
  let addend = toExtended(p);
  let e = scalar;
  while (e > 0n) {
    if (e & 1n) result = addExtended(result, addend);
    addend = addExtended(addend, addend);
    e >>= 1n;
  }
  return toAffine(result);
}

export const multiply = (p: Point, scalar: bigint): Point =>
  multiplyExtended(p, mod(scalar, SUBGROUP_ORDER));

export const equals = (p: Point, q: Point): boolean => p[0] === q[0] && p[1] === q[1];

export function isOnCurve(p: Point): boolean {
  const [x, y] = p;
  if (x < 0n || x >= FIELD || y < 0n || y >= FIELD) return false;
  const xx = mod(x * x);
  const yy = mod(y * y);
  return mod(A_COEFF * xx + yy) === mod(1n + D_COEFF * xx * yy);
}

/** A point of the prime subgroup: on the curve, and killed by its order. */
export const isInSubgroup = (p: Point): boolean =>
  isOnCurve(p) && equals(multiplyExtended(p, SUBGROUP_ORDER), IDENTITY);

/** A uniformly random scalar in [1, l). */
export function randomScalar(): bigint {
  for (;;) {
    const bytes = crypto.getRandomValues(new Uint8Array(40));
    const value = bytesToBigInt(bytes) % SUBGROUP_ORDER;
    if (value !== 0n) return value;
  }
}

function bytesToBigInt(bytes: Uint8Array): bigint {
  let x = 0n;
  for (const b of bytes) x = (x << 8n) | BigInt(b);
  return x;
}

