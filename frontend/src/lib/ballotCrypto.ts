export type Poseidon = (inputs: bigint[]) => bigint;

/** Domain separators, as in the circuit. */
export const TAG_DOMAIN = 1953718116n;
export const EPOCH_DOMAIN = 1701867371n;

/** Poseidon chain over points, seeded with `seed`: HashPoints in the circuit. */
export function hashPoints(poseidon3: Poseidon, seed: bigint, points: readonly Point[]): bigint {
  return points.reduce((h, p) => poseidon3([h, p[0], p[1]]), seed);
}

/** What the circuit takes as `keysHash`: the keys, padded with the identity. */
export function keysHash(poseidon3: Poseidon, keys: readonly Point[], circuitSlots: number): bigint {
  return hashPoints(poseidon3, 0n, padPoints(keys, circuitSlots));
}

/** A ballot's leaf in the ballots tree: BallotLeaf in the circuit. */
export function ballotLeaf(poseidon3: Poseidon, tag: bigint, a: Point, b: readonly Point[]): bigint {
  return hashPoints(poseidon3, poseidon3([tag, a[0], a[1]]), b);
}

/** The voter's tag at step k of their chain in one election. */
export const ballotTag = (poseidon4: Poseidon, secret: bigint, scope: bigint, k: bigint): bigint =>
  poseidon4([TAG_DOMAIN, secret, scope, k]);

/** The voter's tag for one epoch: at most one ballot per voter per epoch. */
export const epochTag = (poseidon4: Poseidon, secret: bigint, scope: bigint, epoch: bigint): bigint =>
  poseidon4([EPOCH_DOMAIN, secret, scope, epoch]);

export const padPoints = (points: readonly Point[], length: number): Point[] =>
  Array.from({ length }, (_, i) => points[i] ?? IDENTITY);

